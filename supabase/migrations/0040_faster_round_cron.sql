-- =============================================================================
-- Частіший cron-воркер раундів (застосовано до робочої БД)
-- =============================================================================
-- Раунд триває 30 c, а серверний воркер rps_autorun (select rps_fill(20))
-- виконувався лише раз на 30 c. Якщо жоден клієнт не активний (усі вкладки на
-- телефоні згорнуті), завершений раунд «завмирав» до наступного тику cron.
-- Тепер, коли tick коштує ~10 мс, ганяємо воркер кожні 10 c — раунди
-- переходять чітко навіть без активних гравців.
select cron.alter_job(
  (select jobid from cron.job where jobname = 'rps_autorun'),
  schedule => '10 seconds'
);
